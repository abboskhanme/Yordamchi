"""Migrations (CONVENTIONS §8; TASKS migration plan): one head, expand-only, `upgrade head` + `alembic check` on empty
`dev.db` and `personal.db`. T40 adds the previous-release fixture DB."""

import ast
import stat
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from alembic.script import ScriptDirectory

from yordamchi.core.paths import BotName
from yordamchi.persistence.base import import_all_models
from yordamchi.persistence.engine import open_database
from yordamchi.persistence.schema import schema_is_current

ROOT = Path(__file__).resolve().parents[2]
MIGRATIONS = ROOT / "migrations"
EXPAND_ONLY_FORBIDDEN = {"drop_table", "drop_column", "drop_index", "drop_constraint", "alter_column", "execute"}


def _config(db_path: Path) -> Config:
    config = Config(str(ROOT / "alembic.ini"))
    config.attributes["db_path"] = db_path
    config.attributes["skip_logging_config"] = True
    return config


def test_the_chain_has_exactly_one_head() -> None:
    assert len(ScriptDirectory(str(MIGRATIONS)).get_heads()) == 1


@pytest.mark.parametrize("revision", sorted((MIGRATIONS / "versions").glob("*.py")), ids=lambda p: p.name)
def test_upgrades_are_expand_only(revision: Path) -> None:
    tree = ast.parse(revision.read_text(encoding="utf-8"))
    upgrade = next(node for node in tree.body if isinstance(node, ast.FunctionDef) and node.name == "upgrade")
    used = {
        node.func.attr
        for node in ast.walk(upgrade)
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute)
    }
    assert used & EXPAND_ONLY_FORBIDDEN == set()


@pytest.mark.parametrize("bot", list(BotName), ids=str)
async def test_upgrade_head_then_check_on_an_empty_db(tmp_path: Path, bot: BotName) -> None:
    db_path = tmp_path / "db" / f"{bot}.db"
    config = _config(db_path)
    command.upgrade(config, "head")
    command.check(config)  # raises AutogenerateDiffsDetected if the models drifted from the chain
    assert stat.S_IMODE(db_path.stat().st_mode) == 0o600

    db = open_database(db_path)
    try:
        assert await schema_is_current(db, MIGRATIONS)
        async with db.engine.connect() as connection:
            tables = await connection.run_sync(lambda sync: set(sync.dialect.get_table_names(sync)))
    finally:
        await db.dispose()
    assert tables - {"alembic_version"} == set(import_all_models().tables)


async def test_an_unmigrated_db_is_not_current(tmp_path: Path) -> None:
    db = open_database(tmp_path / "dev.db")
    try:
        assert not await schema_is_current(db, MIGRATIONS)
    finally:
        await db.dispose()
